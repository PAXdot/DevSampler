/** Text -> 5 banner rows ("█" and spaces). Unknown characters render as a gap. */
export function bannerRows(text: string): string[] {
  const rows = ["", "", "", "", ""];
  for (const ch of text.toLowerCase()) {
    const g = G[ch] ?? G[" "]!;
    for (let r = 0; r < 5; r++) rows[r] += g[r]!.replace(/#/g, "█") + " ";
  }
  return rows.map((r) => r.replace(/\s+$/, ""));
}
